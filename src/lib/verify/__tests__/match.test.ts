import { describe, expect, it } from "vitest";
import { parseReference } from "../extract";
import { formatApa, formatGbt } from "../format";
import { fieldChecks, scoreCandidate, venueSimilarity } from "../match";
import { normalizeText, stripRetractionPrefix, tokenize } from "../normalize";
import type { WorkRecord } from "../types";

const deepLearning: WorkRecord = {
  source: "crossref",
  doi: "10.1038/nature14539",
  title: "Deep learning",
  authors: [
    { family: "LeCun", given: "Yann" },
    { family: "Bengio", given: "Yoshua" },
    { family: "Hinton", given: "Geoffrey" },
  ],
  year: 2015,
  venue: "Nature",
  volume: "521",
  issue: "7553",
  pages: "436-444",
  type: "journal-article",
};

const walters: WorkRecord = {
  source: "crossref",
  doi: "10.1038/s41598-023-41032-5",
  title: "Fabrication and errors in the bibliographic citations generated by ChatGPT",
  authors: [
    { family: "Walters", given: "William H." },
    { family: "Wilder", given: "Esther Isabelle" },
  ],
  year: 2023,
  venue: "Scientific Reports",
  venueShort: "Sci Rep",
  volume: "13",
  issue: "1",
  pages: "14045",
  type: "journal-article",
};

const lstm: WorkRecord = {
  source: "crossref",
  doi: "10.1162/neco.1997.9.8.1735",
  title: "Long Short-Term Memory",
  authors: [
    { family: "Hochreiter", given: "Sepp" },
    { family: "Schmidhuber", given: "Jürgen" },
  ],
  year: 1997,
  venue: "Neural Computation",
  pages: "1735-1780",
};

const ref = (s: string) => parseReference(s, 1);

describe("normalize", () => {
  it("中英文切词", () => {
    expect(tokenize("Deep Learning for the AI")).toEqual(["deep", "learning", "ai"]);
    expect(tokenize("深度学习")).toEqual(["深度", "度学", "学习"]);
    expect(normalizeText("Ｄｅｅｐ　Ｌｅａｒｎｉｎｇ")).toBe("deep learning");
  });
  it("去掉撤稿前缀", () => {
    expect(stripRetractionPrefix("RETRACTED: Ileal-lymphoid-nodular hyperplasia")).toBe("Ileal-lymphoid-nodular hyperplasia");
  });
});

describe("scoreCandidate", () => {
  it("GB/T 写法的真实文献判为同一篇", () => {
    const s = scoreCandidate(ref("LECUN Y, BENGIO Y, HINTON G. Deep learning[J]. Nature, 2015, 521(7553): 436-444."), deepLearning);
    expect(s.same).toBe(true);
    expect(s.yearDiff).toBe(0);
    expect(s.authorOrderOk).toBe(true);
  });

  it("作者顺序写错：仍是同一篇，但顺序不一致", () => {
    const s = scoreCandidate(ref("Bengio, Y., LeCun, Y., & Hinton, G. (2015). Deep learning. Nature, 521(7553), 436–444."), deepLearning);
    expect(s.same).toBe(true);
    expect(s.authorOrderOk).toBe(false);
  });

  it("极短题名 + 作者年份都不对：不能认定为同一篇", () => {
    const s = scoreCandidate(ref("Smith, J. (2020). Deep learning. Journal of Imaginary Studies, 3(2), 1–10."), deepLearning);
    expect(s.same).toBe(false);
  });

  it("长题名逐字一致但作者是编的：认定同一篇，作者字段为 mismatch", () => {
    const r = ref(
      "Smith, J., & Brown, K. (2023). Fabrication and errors in the bibliographic citations generated by ChatGPT. Scientific Reports, 13, 14045.",
    );
    const s = scoreCandidate(r, walters);
    expect(s.same).toBe(true);
    expect(fieldChecks(r, walters, s).find((f) => f.field === "authors")?.status).toBe("mismatch");
  });

  it("期刊写错能识别出来", () => {
    const r = ref("Hochreiter, S., & Schmidhuber, J. (1997). Long short-term memory. Neural Networks, 9(8), 1735–1780.");
    const s = scoreCandidate(r, lstm);
    expect(s.same).toBe(true);
    expect(fieldChecks(r, lstm, s).find((f) => f.field === "venue")?.status).toBe("mismatch");
  });

  it("期刊缩写不算写错", () => {
    expect(venueSimilarity("Sci. Rep.", "Scientific Reports")).toBe(1);
    expect(venueSimilarity("J. Am. Stat. Assoc.", "Journal of the American Statistical Association")).toBe(1);
    expect(venueSimilarity("PNAS", "Proceedings of the National Academy of Sciences")).toBe(1);
    expect(venueSimilarity("IEEE Trans. Pattern Anal. Mach. Intell.", "IEEE Transactions on Pattern Analysis and Machine Intelligence")).toBe(1);
  });

  it("中文作者与题名", () => {
    const rec: WorkRecord = {
      source: "crossref",
      title: "基于深度学习的工程图像识别与分类研究",
      authors: [{ family: "金旭杨" }],
      year: 2025,
      venue: "工程学研究与实用",
    };
    const s = scoreCandidate(ref("金旭杨. 基于深度学习的工程图像识别与分类研究[J]. 工程学研究与实用, 2022."), rec);
    expect(s.same).toBe(true);
    expect(s.yearDiff).toBe(3);
  });
});

describe("format", () => {
  it("GB/T 7714", () => {
    expect(formatGbt(deepLearning)).toBe(
      "LECUN Y, BENGIO Y, HINTON G. Deep learning[J]. Nature, 2015, 521(7553): 436-444. DOI: 10.1038/nature14539.",
    );
  });
  it("APA 7", () => {
    expect(formatApa(walters)).toBe(
      "Walters, W. H., & Wilder, E. I. (2023). Fabrication and errors in the bibliographic citations generated by ChatGPT. Scientific Reports, 13(1), 14045. https://doi.org/10.1038/s41598-023-41032-5",
    );
  });
});
