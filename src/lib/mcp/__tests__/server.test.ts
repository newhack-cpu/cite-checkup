import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

const walters = {
  DOI: "10.1038/s41598-023-41032-5",
  title: ["Fabrication and errors in the bibliographic citations generated by ChatGPT"],
  author: [{ family: "Walters", given: "William H." }, { family: "Wilder", given: "Esther Isabelle" }],
  issued: { "date-parts": [[2023, 9, 7]] }, "container-title": ["Scientific Reports"], volume: "13", "article-number": "14045",
};
const WALTERS = "Walters, W. H., & Wilder, E. I. (2023). Fabrication and errors in the bibliographic citations generated by ChatGPT. Scientific Reports, 13, 14045. https://doi.org/10.1038/s41598-023-41032-5";
const INVENTED = "Smith, J., & Zhang, L. (2021). Deep reinforcement learning for adaptive climate policy optimization. Nature Climate Change, 11(4), 312–320. https://doi.org/10.1038/s41558-021-01234-5";

function stubSources() {
  vi.stubGlobal("fetch", async (input: string) => {
    const url = new URL(input);
    const path = decodeURIComponent(url.pathname);
    if (url.hostname === "api.crossref.org") {
      if (path === "/works/10.1038/s41598-023-41032-5") return Response.json({ message: walters });
      if (path === "/works" || path === "/journals") return Response.json({ message: { items: [] } });
      return new Response("Resource not found.", { status: 404 });
    }
    if (url.hostname === "doi.org") return Response.json([{ DOI: "10.1038/s41558-021-01234-5", status: "DOI does not exist" }]);
    if (url.hostname === "api.openalex.org") {
      if (path === "/works") return Response.json({ results: [] });
      return Response.json({ id: "https://openalex.org/W1", doi: "https://doi.org/10.1038/s41598-023-41032-5", title: walters.title[0], is_retracted: false });
    }
    throw new Error(`Unexpected request: ${url.hostname}${path}`);
  });
}

async function connect() {
  const { createCiteCheckupServer } = await import("../server");
  const server = createCiteCheckupServer();
  const client = new Client({ name: "test-client", version: "1.0.0" });
  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  await Promise.all([server.connect(serverTransport), client.connect(clientTransport)]);
  return client;
}

beforeEach(() => {
  vi.resetModules();
  vi.stubEnv("DEEPSEEK_API_KEY", "");
});
afterEach(() => {
  vi.unstubAllGlobals();
  vi.unstubAllEnvs();
});

describe("cite-checkup MCP server", () => {
  it("lists the two read-only tools with input and output schemas", async () => {
    const client = await connect();
    const { tools } = await client.listTools();
    expect(tools.map((t) => t.name).sort()).toEqual(["check_claim", "verify_references"]);
    const verify = tools.find((t) => t.name === "verify_references")!;
    expect(verify.annotations).toMatchObject({ readOnlyHint: true, openWorldHint: true });
    expect(verify.inputSchema.required).toEqual(["references"]);
    expect(verify.outputSchema?.properties).toHaveProperty("results");
    expect(verify.description).toContain("never from a language model");
  });

  it("verifies references through the protocol and reports progress", async () => {
    stubSources();
    const client = await connect();
    const progress: number[] = [];
    const result = await client.callTool(
      { name: "verify_references", arguments: { references: `[1] ${WALTERS}\n[2] ${INVENTED}` } },
      undefined,
      { onprogress: (p) => progress.push(p.progress) },
    );
    expect(result.isError).toBeFalsy();
    const data = result.structuredContent as { total: number; counts: Record<string, number>; results: { index: number; verdict: string; match?: { doi?: string } }[] };
    expect(data.total).toBe(2);
    expect(data.results.map((r) => [r.index, r.verdict])).toEqual([[1, "verified"], [2, "not_found"]]);
    expect(data.results[0].match?.doi).toBe("10.1038/s41598-023-41032-5");
    expect(data.counts).toMatchObject({ verified: 1, not_found: 1 });
    expect(progress.sort()).toEqual([1, 2]);
    const text = (result.content as { type: string; text: string }[])[0].text;
    expect(text).toContain("[1] 已核实");
    expect(text).toContain("查不到不等于编造");
  });

  it("reports a near match as its own verdict, not as wrong information", async () => {
    const near = { ...walters, DOI: "10.9999/near", title: ["Alpha beta gamma delta epsilon zeta eta theta"] };
    vi.stubGlobal("fetch", async (input: string) => {
      const url = new URL(input);
      if (url.hostname === "api.crossref.org") return Response.json({ message: { items: url.pathname === "/works" ? [near] : [] } });
      if (url.hostname === "api.openalex.org") return Response.json({ results: [] });
      throw new Error(`Unexpected request: ${url.hostname}`);
    });
    const client = await connect();
    const { tools } = await client.listTools();
    expect(tools.find((t) => t.name === "verify_references")!.description).toContain("'near_match'");
    const result = await client.callTool({
      name: "verify_references",
      arguments: { references: "Walters, W. H., & Wilder, E. I. (2023). Alpha beta gamma delta. Scientific Reports, 13, 14045." },
    });
    expect(result.isError).toBeFalsy();
    const data = result.structuredContent as { counts: Record<string, number>; results: { verdict: string; matchStatus?: string; issues: string[] }[] };
    expect(data.results[0]).toMatchObject({ verdict: "near_match", matchStatus: "candidate", issues: [] });
    expect(data.counts).toMatchObject({ near_match: 1, mismatch: 0 });
    const text = (result.content as { type: string; text: string }[])[0].text;
    expect(text).toContain("相近候选 1");
    expect(text).toContain("不算信息有误");
    expect(text).toContain("[1] 相近候选：");
    expect(text).toContain("相近候选（未确认同一篇）");
  });

  it("returns a tool error instead of guessing when no reference can be recognised", async () => {
    const client = await connect();
    const result = await client.callTool({ name: "verify_references", arguments: { references: "references" } });
    expect(result.isError).toBe(true);
    expect((result.content as { text: string }[])[0].text).toContain("没有识别到参考文献");
  });

  it("rejects input that breaks the schema before running anything", async () => {
    const client = await connect();
    const result = await client.callTool({ name: "verify_references", arguments: { references: 42 } });
    expect(result.isError).toBe(true);
  });

  it("reports that claim checking is unavailable without a DeepSeek key, without inventing a verdict", async () => {
    const client = await connect();
    const result = await client.callTool({ name: "check_claim", arguments: { claim: "GPT-3.5 fabricated 55% of citations.", evidence_text: "In our sample, 55% of the GPT-3.5 citations were fabricated." } });
    expect(result.isError).toBe(true);
    expect(result.structuredContent).toMatchObject({ status: "incomplete", verdict: null });
    expect((result.content as { text: string }[])[0].text).toContain("DeepSeek");
  });

  it("requires exactly one evidence source for a claim", async () => {
    vi.stubEnv("DEEPSEEK_API_KEY", "fixture-key-never-real");
    const client = await connect();
    const result = await client.callTool({ name: "check_claim", arguments: { claim: "Some claim.", doi: "10.1038/s41598-023-41032-5", evidence_text: "Some text." } });
    expect(result.isError).toBe(true);
  });
});
